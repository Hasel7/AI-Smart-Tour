export const findSurvivalGuide = (countryName, regionName = "") => {
  if (!countryName) return null;
  
  let guide = null;
  // Try direct match
  if (countrySurvivalGuides[countryName]) {
    guide = countrySurvivalGuides[countryName];
  } else {
    // Try fuzzy match
    for (const [key, value] of Object.entries(countrySurvivalGuides)) {
      if (key.toLowerCase().includes(countryName.toLowerCase()) || countryName.toLowerCase().includes(key.toLowerCase())) {
        guide = value;
        break;
      }
    }
  }

  if (guide && (countryName.toLowerCase().includes("nigeria") || guide.greeting.includes("Nigeria"))) {
    // Deep clone the object so we don't mutate the global standard dictionary permanently
    const localizedGuide = { ...guide };
    const r = regionName.toLowerCase();
    
    // Determine language groups based on Nigerian States
    const igboStates = ["enugu", "anambra", "imo", "abia", "ebonyi"];
    const yorubaStates = ["lagos", "ogun", "oyo", "osun", "ondo", "ekiti", "kwara"];
    const hausaStates = ["kano", "kaduna", "sokoto", "borno", "katsina", "bauchi", "jigawa", "kebbi", "zamfara", "yobe", "gombe", "adamawa", "taraba", "niger", "plateau", "nasarawa", "kogi"];
    
    let dominantLanguage = "pidgin"; // Eastern/Delta states, or unclassified defaults
    if (igboStates.some(s => r.includes(s))) dominantLanguage = "igbo";
    else if (yorubaStates.some(s => r.includes(s))) dominantLanguage = "yoruba";
    else if (hausaStates.some(s => r.includes(s))) dominantLanguage = "hausa";
    
    if (dominantLanguage === "igbo") {
      localizedGuide.phrases = [
         { text: "Nnọọ", meaning: "Welcome" },
         { text: "Kedu?", meaning: "How are you?" },
         { text: "Daalụ", meaning: "Thank you" },
         { text: "Biko", meaning: "Please" },
         { text: "Ego ole?", meaning: "How much?" }
      ];
      localizedGuide.greeting = "Nnọọ na Naijiria!";
    } else if (dominantLanguage === "yoruba") {
      localizedGuide.phrases = [
         { text: "Ẹ kaabọ", meaning: "Welcome" },
         { text: "Bawo ni?", meaning: "How are you?" },
         { text: "Ẹ ṣe", meaning: "Thank you" },
         { text: "Ẹ jọọ", meaning: "Please" },
         { text: "Elo ni?", meaning: "How much?" }
      ];
      localizedGuide.greeting = "Kaabọ si Naijiria!";
    } else if (dominantLanguage === "hausa") {
      localizedGuide.phrases = [
         { text: "Sannu da zuwa", meaning: "Welcome" },
         { text: "Ina kwana?", meaning: "Good morning / How are you?" },
         { text: "Na gode", meaning: "Thank you" },
         { text: "Don Allah", meaning: "Please" },
         { text: "Nawa ne?", meaning: "How much?" }
      ];
      localizedGuide.greeting = "Barka da zuwa Najeriya!";
    } else {
      localizedGuide.phrases = [
         { text: "How far?", meaning: "How are you?" },
         { text: "I dey", meaning: "I am fine" },
         { text: "Abeg", meaning: "Please" },
         { text: "Wetin dey?", meaning: "What's happening?" },
         { text: "No wahala", meaning: "No problem" }
      ];
    }
    return localizedGuide;
  }
  
  return guide;
};
